-- Vidocq port: Mansart's H2Dialect binds java.time.Instant as TIMESTAMP_WITH_TIMEZONE.
-- The original columns were plain TIMESTAMP, which worked because an AttributeConverter
-- mapped Instant to java.util.Date. Mansart has no converter support, so the columns are
-- widened to carry the zone offset.
ALTER TABLE MASTODON_STATUS ALTER COLUMN TWEET_TIME    TIMESTAMP WITH TIME ZONE NOT NULL;
ALTER TABLE MASTODON_STATUS ALTER COLUMN RESPONSE_TIME TIMESTAMP WITH TIME ZONE NOT NULL;

ALTER TABLE BSKY_STATUS     ALTER COLUMN POST_TIME     TIMESTAMP WITH TIME ZONE NOT NULL;
ALTER TABLE BSKY_STATUS     ALTER COLUMN RESPONSE_TIME TIMESTAMP WITH TIME ZONE NOT NULL;

ALTER TABLE TWEET           ALTER COLUMN TWEET_TIME    TIMESTAMP WITH TIME ZONE NOT NULL;
ALTER TABLE TWEET           ALTER COLUMN RESPONSE_TIME TIMESTAMP WITH TIME ZONE NOT NULL;
